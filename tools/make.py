def shape(font, text, size, x=0, y=0):
    scale = size / font["head"].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    parts = []
    stops = [0.0]
    pen_x = 0.0
    for ch in text:
        g = cmap.get(ord(ch))
        if g is None:
            g = cmap[ord(" ")]
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.1f}".rstrip("0").rstrip("."))
        glyphs[g].draw(TransformPen(pen, (scale, 0, 0, -scale, x + pen_x * scale, y)))
        d = pen.getCommands()
        if d:
            parts.append(d)
        pen_x += hmtx[g][0]
        stops.append(pen_x * scale)
    return " ".join(parts), stops


def svg(w, h, label, css, body):
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" role="img" aria-label="{label}">\n'
        f"<style>\n{css}\n@media (prefers-reduced-motion: reduce) {{ * {{ animation: none !important; }} }}\n</style>\n"
        f"{body}\n</svg>\n"
    )


def banner():
    w, h = 1030, 220
    letters = []
    x = 44.0
    for i, ch in enumerate(name):
        d, st = shape(titan, ch, 140, x, 160)
        letters.append(f'<path class="w" style="animation-delay: {i * .16:.2f}s" d="{d}"/>')
        x += st[-1]

    css = """.w { transform-box: fill-box; animation: wave 2.6s ease-in-out infinite; }
@keyframes wave { 0%, 100% { transform: translateY(0); } 50% { transform: translateY(-9px); } }"""

    body = f"""<image width="{w}" height="{h}" preserveAspectRatio="xMidYMid slice" href="data:image/jpeg;base64,{avatar}"/>
<rect width="{w}" height="{h}" fill="#000" fill-opacity=".35"/>
<g fill="#ffffff">{''.join(letters)}</g>"""
    return svg(w, h, name, css, body)


def heading(text, c):
    d, _ = shape(titan, text, 64, 0, 80)
    return svg(960, 112, text, "", f'<path fill="{c["ink"]}" d="{d}"/>')


